# categories asked for but with NO sound yet (documented gap, not faked)
GAPS = {'sedih': 'belum ada SFX sedih di EP01', 'menantang': 'belum ada SFX menantang/tantangan di EP01'}

def ep01_usage():
    p = os.path.join(HERE, '..', '..', 'episodes', 'ep01_jari_keriput', 'ep01', 'audio', 'cues.json')
    try: return {k: sum(1 for e in json.load(open(p))['sfx'] if e['name'] == k) for k in S.SFX}
    except Exception: return {}

if __name__ == '__main__':
    out = os.path.join(HERE, 'library'); use = ep01_usage(); rows = []
    for cat, items in LIB.items():
        d = os.path.join(out, cat); os.makedirs(d, exist_ok=True)
        for name, fn, args, mood, ex in items:
            x = S.SFX[fn](**args).astype(np.float64)
            x = np.concatenate([x, np.zeros(int(.05 * S.SR))])
            pk = float(np.abs(x).max())
            if pk > .98: x *= .98 / pk; pk = .98
            wavfile.write(os.path.join(d, name + '.wav'), S.SR, (x * 32767).astype(np.int16))
            rows.append([cat, f'{cat}/{name}.wav', f'{len(x) / S.SR:.2f}', f'{20 * np.log10(pk + 1e-9):.1f}', f'synth.{"sfx_" if fn not in ("motif_jejak", "motif_transisi") else ""}{fn}({", ".join(f"{k}={v}" for k, v in args.items())})', mood, ex, use.get(fn, 0)])
    for cat, why in GAPS.items():
        d = os.path.join(out, cat); os.makedirs(d, exist_ok=True)
        open(os.path.join(d, 'KOSONG.txt'), 'w').write(f'Kategori "{cat}": {why}.\nBuat fungsi baru di synth.py saat episode membutuhkannya, lalu daftarkan di make_library.py.\n')
        rows.append([cat, '(kosong)', '', '', '', why, '', 0])
    with open(os.path.join(out, 'INDEX.csv'), 'w', newline='') as f:
        w = csv.writer(f); w.writerow(['kategori', 'file', 'durasi_s', 'peak_dBFS', 'sumber_kode', 'fungsi_mood', 'contoh_pakai', 'dipakai_di_EP01_x'])
        w.writerows(rows)
    print(len([r for r in rows if r[1] != '(kosong)']), 'files ->', out)
