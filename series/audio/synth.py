"""Whyscape series audio generator — original backsound + SFX, synthesized from scratch with numpy (no samples, no third-party audio).
Origin: EP01 "Jari Keriput" (v4). Every sound here is generated by code in this file → no third-party license involved.
Usage (per episode, run inside <episode>/audio/):
  python3 <kit>/series/audio/synth.py cues.json   -> music.wav + sfx.wav (placed per cues.json), consumed by mix.py
cues.json keys: duration (s), fade (s), sfx [{name,t,gain,pan,args}], optional: dark [[a,b],…], wait (s, music dropout), lift [[a,b,dB],…]
The EP01 music bed (92 BPM, D dorian, marimba/pluck bass/pad/ticks) is an OPTIONAL preset, not a series requirement.
"""
import json, sys, numpy as np
from scipy.io import wavfile
from scipy.signal import butter, sosfilt

SR = 44100
rng = np.random.default_rng(7)

def env_adsr(n, a=.005, d=.1, s=.0, r=.05, sr=SR):
    t = np.arange(n) / sr; e = np.ones(n)
    A, D, R = int(a * sr), int(d * sr), int(r * sr)
    e[:A] = np.linspace(0, 1, max(A, 1))[:A]
    if D: e[A:A + D] = np.linspace(1, s, D)[:len(e[A:A + D])]
    e[A + D:] = s
    if R and s > 0: e[-R:] *= np.linspace(1, 0, R)
    return e

def lp(x, f, order=2): return sosfilt(butter(order, f / (SR / 2), 'low', output='sos'), x)
def hp(x, f, order=2): return sosfilt(butter(order, f / (SR / 2), 'high', output='sos'), x)
def bp(x, f1, f2, order=2): return sosfilt(butter(order, [f1 / (SR / 2), f2 / (SR / 2)], 'band', output='sos'), x)
def midi(m): return 440 * 2 ** ((m - 69) / 12)

# ---------- instruments ----------
def marimba(f, dur=.9, vel=1.):
    n = int(dur * SR); t = np.arange(n) / SR
    x = (np.sin(2 * np.pi * f * t) * np.exp(-t * 5.5) + .35 * np.sin(2 * np.pi * f * 3.93 * t) * np.exp(-t * 18)
         + .12 * np.sin(2 * np.pi * f * 9.2 * t) * np.exp(-t * 40))
    x[:int(.002 * SR)] *= np.linspace(0, 1, int(.002 * SR))
    return x * vel * .5

def pluck_bass(f, dur=.55, vel=1.):
    n = int(dur * SR); t = np.arange(n) / SR
    x = np.sin(2 * np.pi * f * t) + .45 * np.sin(2 * np.pi * 2 * f * t) * np.exp(-t * 9) + .2 * np.sin(2 * np.pi * 3 * f * t) * np.exp(-t * 14)
    x *= np.exp(-t * 5.0); x[:80] *= np.linspace(0, 1, 80)
    return lp(x, 900) * vel * .55

def pad(freqs, dur, vel=1.):
    n = int(dur * SR); t = np.arange(n) / SR; x = np.zeros(n)
    for f in freqs:
        for det in (-.004, .004):
            ff = f * (1 + det)
            x += np.sin(2 * np.pi * ff * t) + .3 * np.sin(2 * np.pi * 2 * ff * t) + .12 * np.sin(2 * np.pi * 3 * ff * t)
    e = np.minimum(1, t / .8) * np.minimum(1, (dur - t) / .9)
    return lp(x * e, 1400) * vel * .05

def hat(vel=1.):
    n = int(.05 * SR); x = rng.standard_normal(n) * np.exp(-np.arange(n) / SR * 90)
    return hp(x, 7000) * vel * .12

def tick(vel=1.):
    n = int(.06 * SR); t = np.arange(n) / SR
    x = (np.sin(2 * np.pi * 1850 * t) + .6 * np.sin(2 * np.pi * 2720 * t)) * np.exp(-t * 110)
    return x * vel * .16

def kick(vel=1.):
    n = int(.22 * SR); t = np.arange(n) / SR
    f = 50 + 70 * np.exp(-t * 30); ph = 2 * np.pi * np.cumsum(f) / SR
    return np.sin(ph) * np.exp(-t * 16) * vel * .5

def add(buf, x, at, pan=0.):
    i = int(at * SR)
    if i >= len(buf): return
    x = x[:len(buf) - i]
    l, r = np.cos((pan + 1) * np.pi / 4), np.sin((pan + 1) * np.pi / 4)
    buf[i:i + len(x), 0] += x * l * 1.414; buf[i:i + len(x), 1] += x * r * 1.414

# ---------- music ----------
def music(cues):
    dur = cues['duration']; bpm = 92; beat = 60 / bpm; bar = 4 * beat
    out = np.zeros((int(dur * SR) + SR, 2))
    A = [(50, [62, 65, 69]), (46, [58, 62, 65]), (41, [57, 60, 65]), (48, [55, 60, 64])]      # Dm  Bb  F  C
    Bsec = [(43, [55, 58, 62]), (46, [58, 62, 65]), (50, [57, 62, 65]), (45, [57, 61, 64])]   # Gm  Bb  Dm A
    scale = [62, 64, 65, 67, 69, 72, 74]   # D dorian-ish (C natural, B omitted -> curious, open)
    motifs = [[0, None, 2, 4, None, 2, 5, None], [4, None, 2, None, 1, 2, None, 0], [0, 2, 4, None, 6, None, 4, 2], [5, None, 4, 2, None, 1, None, None]]
    t0 = 0.0; b = 0
    while t0 < dur:
        dark = any(a <= t0 < b for a, b in cues.get('dark', []))
        prog_ = Bsec if dark else A
        root, chord = prog_[b % 4]
        # pad (softer in light sections)
        add(out, pad([midi(m) for m in chord], bar + .3, 1.6 if dark else .9), t0, 0)
        # bass: root on 1, fifth-ish pickup on 3+
        if b >= 1:
            add(out, pluck_bass(midi(root)), t0, -.1)
            add(out, pluck_bass(midi(root + 7), .4, .55), t0 + 2.5 * beat, -.1)
        # marimba motif (8ths), lower & sparser when dark
        mot = motifs[(b + (1 if dark else 0)) % 4]
        for k, deg in enumerate(mot):
            if deg is None or (dark and k % 2): continue
            note = scale[deg % 7] - (12 if dark else 0)
            add(out, marimba(midi(note), .8, .55 + .25 * (k == 0)), t0 + k * beat / 2, .35 if k % 2 else -.25)
        # percussion: tick on every beat (clock-like, investigative), hats on off-beats after bar 4, soft kick on 1
        for k in range(4):
            add(out, tick(.55 if k == 0 else .35), t0 + k * beat, .5)
            if b >= 4 and not dark: add(out, hat(.7), t0 + k * beat + beat / 2, -.5)
        if b >= 2: add(out, kick(.55 if dark else .45), t0, 0)
        # nerve pulse arpeggio in the dark section (soft high blips)
        if dark:
            for k in range(8): add(out, marimba(midi(chord[k % 3] + 24), .25, .18), t0 + k * beat / 2 + beat / 4, .6 if k % 2 else -.6)
        t0 += bar; b += 1
    out = out[:int(dur * SR)]
    # "Tunggu" dropout: music stops dead, then breathes back in
    w = cues.get('wait')
    if w is not None:
        g = np.ones(len(out))
        a, c, d = int((w - .06) * SR), int((w + .55) * SR), int((w + 1.4) * SR)
        g[a:c] = 0; g[c:d] = np.linspace(0, 1, d - c)
        out *= g[:, None]
    # ending: short fade so the auto-replay re-enters cleanly
    f = int(cues.get('fade', 1.0) * SR); out[-f:] *= np.linspace(1, 0, f)[:, None] ** 1.5
    return out

# ---------- SFX ----------
def sfx_plunge():   # finger into water
    n = int(.6 * SR); t = np.arange(n) / SR
    body = np.sin(2 * np.pi * (180 + 520 * (1 - np.exp(-t * 14))) * t) * np.exp(-t * 11)
    splash = bp(rng.standard_normal(n), 900, 5000) * np.exp(-t * 16)
    return (.55 * body + .35 * splash) * .9

def sfx_bubbles(count=7, length=.9):
    out = np.zeros(int(length * SR))
    for i in range(count):
        n = int(.07 * SR); t = np.arange(n) / SR; f0 = rng.uniform(500, 1300)
        x = np.sin(2 * np.pi * np.cumsum(f0 * (1 + 2.2 * t / t[-1])) / SR) * np.sin(np.pi * t / t[-1]) ** 2
        at = int(rng.uniform(0, length - .08) * SR); out[at:at + n] += x * rng.uniform(.25, .5)
    return out

def sfx_crinkle(count=7, spacing=.06):
    out = np.zeros(int((count * spacing + .2) * SR))
    for i in range(count):
        n = int(.04 * SR); x = bp(rng.standard_normal(n), 2500, 7000) * np.exp(-np.arange(n) / SR * 120)
        at = int(i * spacing * SR); out[at:at + n] += x * .35
    return out

def sfx_wait():   # tape-stop + low thump
    n = int(.6 * SR); t = np.arange(n) / SR
    f = 330 * (1 - t / t[-1]) ** 2 + 30; ph = 2 * np.pi * np.cumsum(f) / SR
    stop = (np.sin(ph) + .4 * np.sin(2 * ph)) * (1 - t / t[-1]) * .35
    thump = np.sin(2 * np.pi * np.cumsum(60 + 80 * np.exp(-t * 35)) / SR) * np.exp(-t * 9) * .7
    return lp(stop, 2500) + thump

def sfx_dive():   # zoom under the skin: soft filtered swell (single, not a loud whoosh)
    n = int(1.1 * SR); t = np.arange(n) / SR
    noise = rng.standard_normal(n); out = np.zeros(n)
    for k in range(10):   # sweeping band
        a, b_ = int(k * n / 10), int((k + 1) * n / 10)
        fc = 300 + 2600 * (k / 9)
        out[a:b_] = bp(noise, fc * .7, fc * 1.3)[a:b_]
    e = np.sin(np.pi * np.minimum(1, t / 1.05)) ** 2
    tone = np.sin(2 * np.pi * np.cumsum(90 + 40 * t) / SR) * e * .3
    return (out * e * .35 + tone) * .8

def sfx_signal():   # nerve signal: three soft bright blips
    out = np.zeros(int(.6 * SR))
    for i, f in enumerate([1320, 1760, 2093]):
        n = int(.09 * SR); t = np.arange(n) / SR
        x = np.sin(2 * np.pi * f * t) * np.exp(-t * 45) + .3 * np.sin(2 * np.pi * 2 * f * t) * np.exp(-t * 70)
        at = int(i * .13 * SR); out[at:at + n] += x * .3
    return out

def sfx_stamp():
    n = int(.35 * SR); t = np.arange(n) / SR
    thud = np.sin(2 * np.pi * np.cumsum(70 + 90 * np.exp(-t * 40)) / SR) * np.exp(-t * 18)
    slap = bp(rng.standard_normal(n), 600, 3000) * np.exp(-t * 60)
    return thud * .6 + slap * .35

def sfx_knock():   # clipboard landing on the scale pan
    n = int(.25 * SR); t = np.arange(n) / SR
    return (np.sin(2 * np.pi * 420 * t) * np.exp(-t * 40) + .5 * bp(rng.standard_normal(n), 800, 2500) * np.exp(-t * 70)) * .5

def sfx_drip():
    n = int(.25 * SR); t = np.arange(n) / SR
    return np.sin(2 * np.pi * np.cumsum(700 + 900 * t / t[-1]) / SR) * np.exp(-t * 22) * .4

def sfx_scan():   # x-ray scan line: soft rising hum
    n = int(1.6 * SR); t = np.arange(n) / SR
    x = (np.sin(2 * np.pi * np.cumsum(220 + 200 * t / t[-1]) / SR) + .4 * np.sin(2 * np.pi * np.cumsum(440 + 400 * t / t[-1]) / SR))
    return lp(x * np.sin(np.pi * t / t[-1]) ** 2, 1800) * .25

# ---------- v3 additions ----------
def sfx_pop(pitch=1.):          # small pop/click when a key label or icon appears
    n = int(.12 * SR); t = np.arange(n) / SR
    f = (300 + 650 * np.exp(-t * 55)) * pitch
    x = np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t * 38)
    click = hp(rng.standard_normal(n), 3000) * np.exp(-t * 400) * .15
    return (x * .42 + click)

def sfx_whoosh(dur=.55, up=True):   # soft camera / character move (sparing)
    n = int(dur * SR); t = np.arange(n) / SR; noise = rng.standard_normal(n); out = np.zeros(n)
    for k in range(8):
        a, b_ = int(k * n / 8), int((k + 1) * n / 8); fc = (400 + 2200 * (k / 7)) if up else (2600 - 2200 * (k / 7))
        out[a:b_] = bp(noise, fc * .7, fc * 1.3)[a:b_]
    return out * np.sin(np.pi * t / t[-1]) ** 2 * .22

def sfx_ticks(n=6, rate=.17):    # clock ticking while time passes
    out = np.zeros(int((n * rate + .1) * SR))
    for i in range(n):
        m = int(.03 * SR); t = np.arange(m) / SR; f = 2400 if i % 2 else 1900
        x = (np.sin(2 * np.pi * f * t) + .5 * np.sin(2 * np.pi * f * 1.5 * t)) * np.exp(-t * 160)
        at = int(i * rate * SR); out[at:at + m] += x * .22
    return out

def sfx_squeeze():               # vessel narrowing: soft rubbery squeeze
    n = int(.6 * SR); t = np.arange(n) / SR
    f = 230 - 90 * (t / t[-1]) + 8 * np.sin(2 * np.pi * 14 * t)
    x = np.sin(2 * np.pi * np.cumsum(f) / SR) + .3 * np.sin(4 * np.pi * np.cumsum(f) / SR)
    return lp(x * np.sin(np.pi * t / t[-1]) ** 1.5, 900) * .35

def sfx_slowdown():              # blood flow drops
    n = int(.9 * SR); t = np.arange(n) / SR
    x = np.sin(2 * np.pi * np.cumsum(560 * np.exp(-t * 1.3)) / SR) * np.exp(-t * 2.5)
    return lp(x, 1500) * .25

def sfx_pulse():                 # one nerve-signal pulse
    n = int(.2 * SR); t = np.arange(n) / SR
    low = np.sin(2 * np.pi * np.cumsum(140 * np.exp(-t * 8)) / SR) * np.exp(-t * 22)
    blip = np.sin(2 * np.pi * 1480 * t) * np.exp(-t * 60)
    return low * .35 + blip * .18

def sfx_discover():              # "the answer starts to show": three rising notes
    out = np.zeros(int(1.1 * SR))
    for i, m in enumerate([74, 77, 81]):
        x = marimba(midi(m), .9, .9); at = int(i * .11 * SR); out[at:at + len(x)] += x[:len(out) - at]
    n = len(out); t = np.arange(n) / SR
    out += np.sin(2 * np.pi * midi(93) * t) * np.exp(-t * 6) * .05 * (t > .22)
    return out * .7

def sfx_monitor():               # two monitor beeps
    out = np.zeros(int(.5 * SR))
    for i in range(2):
        m = int(.07 * SR); t = np.arange(m) / SR; x = np.sin(2 * np.pi * 1050 * t) * np.minimum(1, (m - np.arange(m)) / 200)
        at = int(i * .18 * SR); out[at:at + m] += x * .16
    return out

def sfx_paper():                 # card / panel flick in
    n = int(.22 * SR); t = np.arange(n) / SR
    return bp(rng.standard_normal(n), 1800, 6500) * np.exp(-t * 26) * np.minimum(1, t / .01) * .3

def sfx_chime():                 # logo chime (opening & closing)
    out = np.zeros(int(1.4 * SR))
    for i, m in enumerate([69, 74]):
        x = marimba(midi(m), 1.3, .8); at = int(i * .09 * SR); out[at:at + len(x)] += x[:len(out) - at]
    t = np.arange(len(out)) / SR
    out += np.sin(2 * np.pi * midi(86) * t) * np.exp(-t * 3.5) * .06
    return out * .6

def motif_jejak():               # series identity motif: two soft footstep taps, then two short notes as the section opens
    out = np.zeros(int(2.4 * SR))
    for at in (0., .4):
        n = int(.16 * SR); t = np.arange(n) / SR
        tap = np.sin(2 * np.pi * np.cumsum(170 * np.exp(-t * 6)) / SR) * np.exp(-t * 30) + .25 * bp(rng.standard_normal(n), 600, 2400) * np.exp(-t * 90)
        i = int(at * SR); out[i:i + n] += tap * .55
    for at, m in ((1.55, 74), (1.76, 81)):
        x = marimba(midi(m), .6, .9); i = int(at * SR); out[i:i + len(x)] += x[:len(out) - i]
    return out * .8

def motif_transisi():          # SERIES SIGNATURE (v4): 3 soft footstep taps on the beat, a short rise, then two notes as the portal opens
    out = np.zeros(int(1.7 * SR))
    for i, at in enumerate((0., .22, .44)):
        n = int(.16 * SR); t = np.arange(n) / SR
        tap = np.sin(2 * np.pi * np.cumsum((175 + 12 * i) * np.exp(-t * 6)) / SR) * np.exp(-t * 28) + .22 * bp(rng.standard_normal(n), 700, 2600) * np.exp(-t * 90)
        j = int(at * SR); out[j:j + n] += tap * .6
    n = int(.36 * SR); t = np.arange(n) / SR; j = int(.46 * SR)
    rise = sum(np.sin(2 * np.pi * np.cumsum(f * (1 + .5 * t / t[-1])) / SR) for f in (587, 880)) * (t / t[-1]) ** 2 * .07
    out[j:j + n] += lp(rise, 3000)
    for at, m in ((.82, 74), (1.0, 81)):
        x = marimba(midi(m), .7, .95); j = int(at * SR); out[j:j + len(x)] += x[:len(out) - j]
    return out * .85

def sfx_ripple():
    n = int(.5 * SR); t = np.arange(n) / SR
    return np.sin(2 * np.pi * np.cumsum(380 + 500 * t / t[-1]) / SR) * np.exp(-t * 9) * .22

SFX = {'plunge': sfx_plunge, 'bubbles': sfx_bubbles, 'crinkle': sfx_crinkle, 'wait': sfx_wait, 'dive': sfx_dive, 'signal': sfx_signal,
       'stamp': sfx_stamp, 'knock': sfx_knock, 'drip': sfx_drip, 'scan': sfx_scan,
       'pop': sfx_pop, 'whoosh': sfx_whoosh, 'ticks': sfx_ticks, 'squeeze': sfx_squeeze, 'slowdown': sfx_slowdown, 'pulse': sfx_pulse,
       'discover': sfx_discover, 'monitor': sfx_monitor, 'paper': sfx_paper, 'chime': sfx_chime, 'motif_jejak': motif_jejak, 'motif_transisi': motif_transisi, 'ripple': sfx_ripple}

if __name__ == '__main__':
    cues = json.load(open(sys.argv[1]))
    m = music(cues)
    wavfile.write('music.wav', SR, (m / (np.abs(m).max() + 1e-9) * .8).astype(np.float32))
