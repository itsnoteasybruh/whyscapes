    for ev in cues['sfx']:
        x = SFX[ev['name']](**ev.get('args', {})); add(sfx, x * ev.get('gain', 1.), ev['t'], ev.get('pan', 0.))
    wavfile.write('sfx.wav', SR, sfx.astype(np.float32))
    print('music', m.shape[0] / SR, 's; sfx events', len(cues['sfx']))
